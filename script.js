const flat = args => args.flat(Infinity);
const nums = args => flat(args).filter(v => typeof v === "number");
function criteria(cr) {
  const m = String(cr).match(/^(<=|>=|<>|<|>|=)?(.*)$/);
  const op = m[1] || "=", raw = m[2], n = Number(raw), isNum = raw !== "" && !isNaN(n);
  return v => {
    const a = isNum ? v : String(v).toLowerCase(), b = isNum ? n : raw.toLowerCase();
    if (isNum && typeof v !== "number") return op === "<>";
    switch (op) { case ">": return a > b; case "<": return a < b; case ">=": return a >= b; case "<=": return a <= b; case "<>": return a != b; default: return a == b; }
  };
}
const FUNCS = {
  "СУММ": a => nums(a).reduce((s, x) => s + x, 0),
  "СРЗНАЧ": a => { const n = nums(a); if (!n.length) throw "#ДЕЛ/0!"; return n.reduce((s, x) => s + x, 0) / n.length; },
  "МАКС": a => Math.max(...nums(a)),
  "МИН": a => Math.min(...nums(a)),
  "СЧЁТ": a => nums(a).length,
  "ЕСЛИ": a => (a[0] ? a[1] : (a.length > 2 ? a[2] : false)),
  "И": a => flat(a).every(Boolean),
  "ИЛИ": a => flat(a).some(Boolean),
  "ОКРУГЛ": a => { const p = Math.pow(10, a[1] || 0); return Math.round(a[0] * p + Number.EPSILON) / p; },
  "СЧЁТЕСЛИ": a => flat([a[0]]).filter(criteria(a[1])).length,
  "СУММЕСЛИ": a => {
    const r = flat([a[0]]), s = a[2] ? flat([a[2]]) : r, f = criteria(a[1]);
    return r.reduce((acc, v, i) => acc + (f(v) && typeof s[i] === "number" ? s[i] : 0), 0);
  },
  "ABS": a => Math.abs(a[0]),
  "КОРЕНЬ": a => Math.sqrt(a[0]),
  "СТЕПЕНЬ": a => Math.pow(a[0], a[1])
};

function tokenize(src) {
  const toks = []; let i = 0;
  const re = {
    space: /^\s+/, num: /^\d+(\.\d+)?/, str: /^"([^"]*)"/,
    range: /^\$?[A-Z]+\$?\d+:\$?[A-Z]+\$?\d+/, ref: /^\$?[A-Z]+\$?\d+/,
    fn: /^[A-Za-zА-Яа-яЁё][A-Za-zА-Яа-яЁё0-9.]*(?=\s*\()/,
    op: /^(<=|>=|<>|[-+*\/^&=<>(),;:%])/
  };
  while (i < src.length) {
    const rest = src.slice(i); let m;
    if ((m = rest.match(re.space))) { i += m[0].length; continue; }
    if ((m = rest.match(re.str))) toks.push({ t: "str", v: m[1] });
    else if ((m = rest.match(re.num))) toks.push({ t: "num", v: parseFloat(m[0]) });
    else if ((m = rest.match(re.fn))) toks.push({ t: "fn", v: m[0].toUpperCase() });
    else if ((m = rest.toUpperCase().match(re.range))) toks.push({ t: "range", v: m[0].replace(/\$/g, "") });
    else if ((m = rest.toUpperCase().match(re.ref))) toks.push({ t: "ref", v: m[0].replace(/\$/g, "") });
    else if ((m = rest.match(re.op))) toks.push({ t: "op", v: m[0] });
    else throw "Түшүнүксүз белги: «" + rest[0] + "»";
    i += m[0].length;
  }
  return toks;
}

function evalFormula(src, used) {
  if (!src.startsWith("=")) throw "Формула = белгиси менен башталышы керек.";
  const toks = tokenize(src.slice(1)); let p = 0;
  const peek = () => toks[p], take = () => toks[p++];
  const expect = v => { const t = take(); if (!t || t.v !== v) throw `«${v}» күтүлгөн.`; };
  const cell = r => { used.add(r); const v = SHEET[r]; return v === undefined ? 0 : v; };
  const range = r => {
    const [a, b] = r.split(":"), ma = a.match(/([A-Z]+)(\d+)/), mb = b.match(/([A-Z]+)(\d+)/);
    const out = [];
    for (let row = Math.min(+ma[2], +mb[2]); row <= Math.max(+ma[2], +mb[2]); row++)
      for (let c = Math.min(colIdx(ma[1]), colIdx(mb[1])); c <= Math.max(colIdx(ma[1]), colIdx(mb[1])); c++) {
        const ref = colName(c) + row; used.add(ref); if (SHEET[ref] !== undefined) out.push(SHEET[ref]);
      }
    return out;
  };
  const isOp = v => peek() && peek().t === "op" && peek().v === v;
  const num = v => { if (Array.isArray(v)) throw "Диапазонду функциянын ичинде гана колдонуңуз."; if (typeof v === "boolean") return v ? 1 : 0; if (typeof v === "string") { const n = Number(v); if (v === "" || isNaN(n)) throw "#ЗНАЧ! — текст менен арифметикалык амал."; return n; } return v; };

  function comparison() {
    let l = concat();
    while (peek() && peek().t === "op" && ["=", "<>", "<", ">", "<=", ">="].includes(peek().v)) {
      const op = take().v, r = concat();
      const a = typeof l === "string" ? l.toLowerCase() : l, b = typeof r === "string" ? r.toLowerCase() : r;
      l = { "=": a == b, "<>": a != b, "<": a < b, ">": a > b, "<=": a <= b, ">=": a >= b }[op];
    }
    return l;
  }
  function concat() { let l = additive(); while (isOp("&")) { take(); l = String(l) + String(additive()); } return l; }
  function additive() {
    let l = term();
    while (isOp("+") || isOp("-")) { const op = take().v, r = term(); l = op === "+" ? num(l) + num(r) : num(l) - num(r); }
    return l;
  }
  function term() {
    let l = power();
    while (isOp("*") || isOp("/")) {
      const op = take().v, r = power();
      if (op === "/" && num(r) === 0) throw "#ДЕЛ/0! — нөлгө бөлүү.";
      l = op === "*" ? num(l) * num(r) : num(l) / num(r);
    }
    return l;
  }
  function power() { let l = unary(); while (isOp("^")) { take(); l = Math.pow(num(l), num(unary())); } return l; }
  function unary() {
    if (isOp("-")) { take(); return -num(unary()); }
    if (isOp("+")) { take(); return num(unary()); }
    let v = primary();
    if (isOp("%")) { take(); v = num(v) / 100; }
    return v;
  }
  function primary() {
    const t = take();
    if (!t) throw "Формула толук эмес.";
    if (t.t === "num" || t.t === "str") return t.v;
    if (t.t === "ref") return cell(t.v);
    if (t.t === "range") return range(t.v);
    if (t.t === "fn") {
      const name = FN_ALIAS[t.v] || t.v;
      if (name === "ИСТИНА" || name === "TRUE") { expect("("); expect(")"); return true; }
      if (name === "ЛОЖЬ" || name === "FALSE") { expect("("); expect(")"); return false; }
      const f = FUNCS[name]; if (!f) throw `#ИМЯ? — «${t.v}» функциясы табылган жок.`;
      expect("("); const args = [];
      if (!isOp(")")) { args.push(comparison()); while (isOp(";") || isOp(",")) { take(); args.push(comparison()); } }
      expect(")");
      return f(args);
    }
    if (t.t === "op" && t.v === "(") { const v = comparison(); expect(")"); return v; }
    throw `Күтүлбөгөн белги: «${t.v}»`;
  }
  const result = comparison();
  if (p < toks.length) throw `Артык белги: «${toks[p].v}»`;
  if (Array.isArray(result)) throw "Диапазонду СУММ сыяктуу функциянын ичинде колдонуңуз.";
  return result;
}

