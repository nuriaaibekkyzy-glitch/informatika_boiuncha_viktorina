const tf = {
  pool: [], cur: null, score: 0, streak: 0, best: 0, left: 60, timer: null, mistakes: [], answered: 0, lock: false,
  start() {
    this.pool = shuffle(pick($("#tfModule").value, "tf"));
    this.score = 0; this.streak = 0; this.best = 0; this.left = 60; this.mistakes = []; this.answered = 0; this.lock = false;
    $("#tfIntro").classList.add("hidden"); $("#tfEnd").classList.add("hidden"); $("#tfPlay").classList.remove("hidden");
    $("#tfFlash").textContent = "";
    this.next(); this.update();
    this.timer = setInterval(() => { this.left--; this.update(); if (this.left <= 0) this.stop(); }, 1000);
  },
  next() {
    if (!this.pool.length) this.pool = shuffle(pick($("#tfModule").value, "tf"));
    this.cur = this.pool.pop();
    const c = $("#tfCard"); c.className = "tf-card"; c.textContent = this.cur.s;
  },
  update() {
    $("#tfTime").textContent = "⏱ " + this.left;
    $("#tfScore").textContent = "Упай: " + this.score;
    $("#tfStreak").textContent = "Катар: " + this.streak;
  },
  answer(v) {
    if (this.lock || !this.timer) return;
    this.lock = true; this.answered++;
    const right = v === this.cur.v;
    if (right) { this.score++; this.streak++; this.best = Math.max(this.best, this.streak); }
    else { this.score--; this.streak = 0; this.mistakes.push(this.cur); }
    $("#tfCard").classList.add(right ? "ok" : "bad");
    $("#tfFlash").textContent = right ? "✓ Туура" : "✗ " + (this.cur.v ? "Бул ырастоо — чын." : (this.cur.e || "Бул ырастоо — жалган."));
    this.update();
    setTimeout(() => { this.lock = false; if (this.timer) this.next(); }, right ? 350 : 1100);
  },
  stop(silent) {
    if (!this.timer) return;
    clearInterval(this.timer); this.timer = null;
    if (silent) { $("#tfPlay").classList.add("hidden"); $("#tfIntro").classList.remove("hidden"); return; }
    $("#tfPlay").classList.add("hidden"); $("#tfEnd").classList.remove("hidden");
    $("#tfBig").textContent = this.score;
    $("#tfEndText").innerHTML = `${this.answered} ырастоого жооп бердиңиз · эң узун туура катар: <b>${this.best}</b>`;
    $("#tfMistakes").innerHTML = this.mistakes.length
      ? "<h3>Ката кетирилген ырастоолор</h3>" + this.mistakes.map(m => `<div class="review-item"><b>${esc(m.s)}</b>${m.v ? "Бул — чын." : "Бул — жалган. " + esc(m.e || "")}</div>`).join("")
      : "";
    saveResult("Чынбы-жалганбы", $("#tfModule").value, Math.max(0, this.score), Math.max(1, this.answered));
  }
};
